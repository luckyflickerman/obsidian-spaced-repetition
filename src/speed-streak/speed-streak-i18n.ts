export function isPolish(): boolean {
    let locale = "";
    try {
        locale = LocaleManagerInstance.getInstance().currentLocale ?? "";
    } catch {
        try {
            locale = moment.locale() ?? "";
        } catch {
            locale = "";
        }
    }
    return locale.toLowerCase().startsWith("pl");
}

export function ss(key: Keys, params?: Record<string, string | number>): string {
    let text = (isPolish() ? PL[key] : EN[key]) ?? EN[key];
    if (params) {
        for (const [k, v] of Object.entries(params)) {
            text = text.split("${" + k + "}").join(String(v));
        }
    }
    return text;
}
